-- The buildings the family holes up in and the stashes (Story/Sites), made from the list.
local Sites = require "KnoxMobile/Story/Sites"
local KIND = { house = "a casa", church = "a igreja", school = "a escola", pharmacy = "a farmácia", gas = "o posto de gasolina", police = "a delegacia" }
local PATTERN = "{kind} na {street} em {town}"
for _, list in ipairs({ Sites.family, Sites.quests }) do
    for _, s in ipairs(list) do
        local street, town = tostring(s.name):match("^the .- on (.+) in (.+)$")
        if street and KIND[s.kind] and D[s.name] == nil then
            D[s.name] = (PATTERN:gsub("{kind}", function() return KIND[s.kind] end)
                :gsub("{street}", function() return street end):gsub("{town}", function() return D[town] or town end))
        end
    end
end

return D
